# String to Integer
num_str = "10"
num_int = int(num_str)
print("String to Integer:", num_int)     # Output: 10

# Float to Integer
num_float = 5.7
num_int2 = int(num_float)
print("Float to Integer:", num_int2)     # Output: 5 (decimal part is removed)

# Integer to Float
num = 7
num_float2 = float(num)
print("Integer to Float:", num_float2)   # Output: 7.0